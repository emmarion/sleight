#!/usr/bin/env python3
"""Writes the sample programs under bench/, each stressing one part of the elaborator; deterministic, so the
files are checked in and this script only needs re-running when it changes."""
import os
here = os.path.dirname(os.path.abspath(__file__))

def write(name, text):
    with open(os.path.join(here, name), 'w') as f:
        f.write(text)

# many_adts: many opened Matchables, then functions matching on each with an else: every branch entry and
# every else coverage probe restores the opened-objects invariant (DESIGN.md 19) against all of them.
n = 120
out = ["; generated by bench/gen.py: many ADTs, then a match on each (the opened-objects invariant)", "(def-lvl L)"]
for i in range(n):
    out.append(f"(def-adts $ (T{i} : -> Type)\n  enum\n  (many TA{i} : -> (T{i}))\n  (many TB{i} : (many (Nat) n) -> (T{i}))\n  (many TC{i} : (many (Nat) n) (many (Nat) m) -> (T{i}))\n  (many TD{i} : -> (T{i})))")
for i in range(n):
    out.append(f"(def-fns L $ (many f{i} : (many (T{i}) x) -> (many (Nat) r))\n  (match many x _\n    ((TA{i}) 0)\n    ((TB{i} n) n)\n    ((TC{i} n m) (nat-add n m))\n    (else 1)))")
out.append(f"(f{n-1} (TC{n-1} 1 2))")
write("many_adts.sl", "\n".join(out) + "\n")

# long_body: one function body with many lets over calls whose _ arguments are metas, so the fact table grows
# by a rule per solved meta and per binder along the body (the rules list and canonicalization).
m = 150
out = ["; generated by bench/gen.py: a long body of lets over calls with _ arguments (rules and canonicalization)",
       "(def-lvl L)",
       "(def-fns L $ (many step : (erased Type A) (many (List A) xs) (many A x) -> (many (List A) r))\n  (Cons _ x xs))",
       "(def-fns L $ (many len : (erased Type A) (subterm many (List A) xs) -> (many (Nat) n))\n  (match many xs _ ((Nil a) 0) ((Cons a x rest) (Succ $ notail $ len _ rest))))",
       "(def-lvl M)",
       "(let ((erased plm)) (prove-predates L M))",
       "(def-fns M $ (many body : (many (Nat) n) -> (many (Nat) r))",
       "  (let ((many xs0)) (Nil (Nat)))"]
for i in range(m):
    out.append(f"  (let ((many xs{i+1})) (step _ xs{i} n))")
out.append(f"  (len _ xs{m}))")
out.append("(body 3)")
write("long_body.sl", "\n".join(out) + "\n")

# wide_scope: many top-level definitions, then a body naming them: name lookup across a wide scope.
w = 400
out = ["; generated by bench/gen.py: many top-level names, then a body naming them (name lookup)", "(def-lvl L)"]
for i in range(w):
    out.append(f"(def-fns L $ (many g{i} : (many (Nat) n) -> (many (Nat) r))\n  (nat-add n {i}))")
out.append("(def-lvl M)")
out.append("(let ((erased plm)) (prove-predates L M))")
out.append("(def-fns M $ (many total : (many (Nat) n) -> (many (Nat) r))")
for i in range(w):
    out.append(f"  (let ((many v{i})) (g{i} n))")
out.append("  (nat-add " + " $ nat-add ".join(f"v{i}" for i in range(w - 1)) + f" v{w-1}))")
out.append("(total 1)")
write("wide_scope.sl", "\n".join(out) + "\n")

# comptime_garbage / comptime_live: the compile-time interpreter builds a long list, which one program
# folds away and the other keeps. The first is almost all garbage, so it measures what the store does with
# values nothing reaches; the second keeps them all reachable, so it measures the emitter's walk and sort.
k = 12000
body = ("(def-lvl GL)\n"
        "(def-fns GL $ (many gen-list : (subterm many (Nat) n) (many (List $ Nat) acc) -> (many (List $ Nat) r))\n"
        "  (match many n _ ((Zero) acc) ((Succ j) (tail (gen-list j (Cons (Nat) j acc))))))\n")
write("comptime_garbage.sl",
      "; generated by bench/gen.py: a long list built at compile time and folded away, so nothing reaches it\n"
      + body
      + "(def-fns GL $ (many gen-total : (subterm many (List $ Nat) xs) (many (Nat) acc) -> (many (Nat) r))\n"
        "  (match many xs _ ((Nil a) acc) ((Cons a x rest) (tail (gen-total rest (nat-add x acc))))))\n"
      + f"(let ((many t)) (gen-total (gen-list {k} (Nil (Nat))) 0))\nt\n")
write("comptime_live.sl",
      "; generated by bench/gen.py: the same list kept as a Const and as the final value, so every block of it\n"
      "; is reachable and the emitter must walk, order and write all of them\n"
      + body
      + f"(let ((many big)) (gen-list {k} (Nil (Nat))))\nbig\n")

fns, per, c, m = 16, 500, 32, 2000
out = ["; generated by bench/gen.py: unique uses left in the uses map by earlier bodies, then many wide matches",
       "(def-adts $ (Wide : -> Type)\n  enum\n" + "\n".join(f"  (many W{i} : -> (Wide))" for i in range(c)) + ")"]
for f in range(fns):
    out.append(f"(def-fns _ $ (many setup{f} : (many (Nat) n) -> (many (Nat) r))")
    for i in range(per):
        out.append(f"  (let ((unique u{i})) (Zero))\n  (let ((many _)) (share u{i}))")
    out.append("  n)")
out.append("(def-fns _ $ (many body : (many (Wide) w) -> (many (Wide) r))")
branches = " ".join(f"((W{i}) (values))" for i in range(c))
out += [f"  (let () (match many w () {branches}))"] * m
out.append("  w)\n(body (W0))")
write("uses_join.sl", "\n".join(out) + "\n")
print("written")
