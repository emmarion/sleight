import os, resource, subprocess, sys
HEADER = ('; Generated by prelude.py from ../lib/prelude.sl: the forms that the Lean runner accepts, in order{}.\n'
          '; Regenerate after the runner learns more.\n\n')
src = open(sys.argv[1]).read()
binary, out, out_full = sys.argv[2], sys.argv[3], sys.argv[4]
# split into top-level forms with their preceding comment lines
forms = []; i = 0; depth = 0; start = None; n = len(src)
while i < n:
    c = src[i]
    if c == ';':
        j = src.find('\n', i); j = n if j < 0 else j
        if depth == 0 and src[i:i+2] == ';!': forms.append(src[i:j])
        i = j; continue
    if c == '"':
        j = i + 1
        while src[j] != '"':
            j += 2 if src[j] == '\\' else 1
        i = j + 1; continue
    if c == '#' and src[i+1:i+2] == '\\':
        i += 3; continue
    if c == '(':
        if depth == 0: start = i
        depth += 1
    elif c == ')':
        depth -= 1
        if depth == 0: forms.append(src[start:i+1])
    i += 1
tmp = out + '.try.sl'
def accepts(fs, mode):
    open(tmp, 'w').write('\n\n'.join(fs) + '\n')
    try:
        r = subprocess.run([binary, '--no-prelude'] + mode + [tmp], capture_output=True, text=True, timeout=10,
            preexec_fn=lambda: resource.setrlimit(resource.RLIMIT_AS, (8 << 30, 8 << 30))).stdout
    except subprocess.TimeoutExpired:
        r = 'x: stuck: timeout'
    body = r.split(': ', 1)[1] if ': ' in r else r
    return bool(r) and not (body.startswith('error') or body.startswith('refused') or body.startswith('stuck')), body
kept, kept_full = [], []
for f in forms:
    ok, body = accepts(kept + [f], [])
    if ok:
        kept.append(f)
        if accepts(kept_full + [f], ['--full'])[0]:
            kept_full.append(f)
        else:
            print('full run drops:', f.split('\n')[0][:90], file=sys.stderr)
    else:
        print('dropped:', f.split('\n')[0][:90], '|', body.strip()[:80], file=sys.stderr)
open(out, 'w').write(HEADER.format('') + '\n\n'.join(kept) + '\n')
open(out_full, 'w').write(HEADER.format(' and whose full run (--full) finishes') + '\n\n'.join(kept_full) + '\n')
os.remove(tmp)
print(len(kept), 'and', len(kept_full), 'of', len(forms), 'kept', file=sys.stderr)
