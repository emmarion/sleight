import os, re, resource, subprocess, sys
HEADER = ('; Generated by prelude.py from ../lib/prelude.sl: the forms that the Lean runner accepts, in order,\n'
          '; with extern markers removed. Regenerate after the runner learns more.\n\n')
src = open(sys.argv[1]).read()
binary, out = sys.argv[2], sys.argv[3]
# split into top-level forms with their preceding comment lines
forms = []; i = 0; depth = 0; start = None; n = len(src)
while i < n:
    c = src[i]
    if c == ';':
        j = src.find('\n', i); i = n if j < 0 else j; continue
    if c == '"':
        j = i + 1
        while src[j] != '"':
            j += 2 if src[j] == '\\' else 1
        i = j + 1; continue
    if c == '#' and src[i+1:i+2] == '\\':
        i += 3; continue
    if c == '(':
        if depth == 0: start = i
        depth += 1
    elif c == ')':
        depth -= 1
        if depth == 0: forms.append(src[start:i+1])
    i += 1
def clean(f):
    f = re.sub(r'\benum extern\b', 'enum', f)
    f = re.sub(r'\((many|erased) extern ', r'(\1 ', f)
    return f
kept = []
tmp = out + '.try.sl'
for f in forms:
    f = clean(f)
    open(tmp, 'w').write('\n\n'.join(kept + [f]) + '\n')
    try:
        r = subprocess.run([binary, '--no-prelude', '--full', tmp], capture_output=True, text=True, timeout=10,
            preexec_fn=lambda: resource.setrlimit(resource.RLIMIT_AS, (8 << 30, 8 << 30))).stdout
    except subprocess.TimeoutExpired:
        r = 'x: stuck: timeout'
    body = r.split(': ', 1)[1] if ': ' in r else r
    if r and not (body.startswith('error') or body.startswith('refused') or body.startswith('stuck')):
        kept.append(f)
    else:
        print('dropped:', f.split('\n')[0][:90], '|', body.strip()[:80], file=sys.stderr)
open(out, 'w').write(HEADER + '\n\n'.join(kept) + '\n')
os.remove(tmp)
print(len(kept), 'of', len(forms), 'kept', file=sys.stderr)
