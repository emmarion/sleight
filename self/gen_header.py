# Regenerates self/header.sl: the OCaml runtime of every compiled program, lib/ffi_core.ml and
# lib/driver_core.ml wrapped as modules followed by self/runtime.ml, as one SL Rope of string literals, one per line,
# and lib/ffi_templates.txt as a second (extern-templates).
import os
here = os.path.dirname(os.path.abspath(__file__))
def read(*path):
    return open(os.path.join(here, *path)).read().rstrip("\n")
text = "\n".join(['[@@@warning "-a"]', "module Ffi_core = struct", read("..", "lib", "ffi_core.ml"), "end",
                  "module Driver_core = struct", read("..", "lib", "driver_core.ml"), "end", read("runtime.ml")])
def lit(l):
    return '(RStr "' + l.replace("\\", "\\\\").replace('"', '\\"') + '\\n")'
out = ["; self/header.sl -- generated by self/gen_header.py from lib/ffi_core.ml, lib/driver_core.ml and self/runtime.ml; do not edit by hand.", "",
       "(let (many runtime-header)"] + ["  %sRCat %s" % ("(" if i == 0 else "$ ", lit(l)) for i, l in enumerate(text.split("\n"))]
out.append("  $ REmpty))")
templates = read("..", "lib", "ffi_templates.txt")
out += ["", "(let (many extern-templates)"] + ["  %sRCat %s" % ("(" if i == 0 else "$ ", lit(l)) for i, l in enumerate(templates.split("\n"))] + ["  $ REmpty))"]
open(os.path.join(here, "header.sl"), "w").write("\n".join(out) + "\n")
