# Regenerates self/header.sl, which git ignores: the OCaml runtime of every compiled program, lib/ffi_core.ml and
# lib/driver_core.ml wrapped as modules followed by self/runtime.ml (runtime-header), lib/ffi_templates.txt
# (extern-templates), lib/specials.txt (specials-help) and lib/prelude.sl (prelude-source), each as one SL String literal.
import os
here = os.path.dirname(os.path.abspath(__file__))
def read(*path):
    return open(os.path.join(here, *path)).read().rstrip("\n")
def lit(name, text):
    return '\n(let ((many %s)) "%s")' % (name, text.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n") + "\\n")
runtime = "\n".join(['[@@@warning "-a"]', "module Ffi_core = struct", read("..", "lib", "ffi_core.ml"), "end",
                     "module Driver_core = struct", read("..", "lib", "driver_core.ml"), "end", read("runtime.ml")])
out = ["; self/header.sl -- generated by self/gen_header.py from lib/ffi_core.ml, lib/driver_core.ml, self/runtime.ml, lib/ffi_templates.txt, lib/specials.txt and lib/prelude.sl; do not edit by hand.",
       lit("runtime-header", runtime), lit("extern-templates", read("..", "lib", "ffi_templates.txt")), lit("specials-help", read("..", "lib", "specials.txt")), lit("prelude-source", read("..", "lib", "prelude.sl"))]
open(os.path.join(here, "header.sl"), "w").write("\n".join(out) + "\n")
