# Regenerates self/header.sl, the OCaml runtime of self/runtime.ml as SL string literals, one per line.
import os
here = os.path.dirname(os.path.abspath(__file__))
lines = open(os.path.join(here, "runtime.ml")).read().rstrip("\n").split("\n")
def lit(l):
    return '"' + l.replace("\\", "\\\\").replace('"', '\\"') + '"'
out = ["; self/header.sl -- generated by self/gen_header.py from self/runtime.ml; do not edit by hand.", "",
       "(let (many runtime-header)", "  (Cons (String) " + lit(lines[0])]
for l in lines[1:]:
    out.append("  $ Cons (String) " + lit(l))
out.append("  (Nil (String))))")
open(os.path.join(here, "header.sl"), "w").write("\n".join(out) + "\n")
