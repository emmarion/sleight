# Regenerates self/header.sl: the OCaml runtime of every compiled program, lib/ffi_core.ml and
# lib/driver_core.ml wrapped as modules followed by self/runtime.ml, as one SL Rope of string literals, one per line,
# lib/ffi_templates.txt as a second (extern-templates), and lib/prelude.sl as one String literal (prelude-source).
import os
here = os.path.dirname(os.path.abspath(__file__))
def read(*path):
    return open(os.path.join(here, *path)).read().rstrip("\n")
text = "\n".join(['[@@@warning "-a"]', "module Ffi_core = struct", read("..", "lib", "ffi_core.ml"), "end",
                  "module Driver_core = struct", read("..", "lib", "driver_core.ml"), "end", read("runtime.ml")])
def esc(s):
    return s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n")
def lit(l):
    return '(RStr "' + esc(l + "\n") + '")'
def rope(name, text):
    return ["", "(let ((many %s))" % name] + ["  $ RCat %s" % lit(l) for l in text.split("\n")] + ["  $ REmpty)"]
out = ["; self/header.sl -- generated by self/gen_header.py from lib/ffi_core.ml, lib/driver_core.ml, self/runtime.ml, lib/ffi_templates.txt and lib/prelude.sl; do not edit by hand."]
out += rope("runtime-header", text) + rope("extern-templates", read("..", "lib", "ffi_templates.txt")) + ["", '(let ((many prelude-source)) "%s")' % esc(read("..", "lib", "prelude.sl") + "\n")]
open(os.path.join(here, "header.sl"), "w").write("\n".join(out) + "\n")
